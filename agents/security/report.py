"""Turns what happened with each attack into a report that can be checked in CI.

It holds nothing that changes between runs, so a difference from the committed report means that
what stops an attack has changed, which someone should look at.

Author: Ignacio Rodriguez Caro <rnachoccontact@gmail.com>
"""

from collections import Counter
from dataclasses import dataclass

import httpx2

from security.bank import Attack, Breach, Stack, Stopper


@dataclass(frozen=True)
class Result:
    """What happened with an attack.

    Attributes:
        attack: The attack.
        stopper: What stopped it, or nothing if it was not stopped.
        note: What went wrong, if it was not stopped.
    """

    attack: Attack
    stopper: Stopper | None
    note: str = ""


def run_attack(attack: Attack, stack: Stack) -> Result:
    """Try an attack. Anything other than being stopped counts as a breach.

    Args:
        attack: The attack.
        stack: The stack.

    Returns:
        What happened.
    """
    try:
        return Result(attack, attack.run(stack))
    except Breach as breach:
        return Result(attack, None, str(breach))
    except (httpx2.HTTPError, KeyError, ValueError, IndexError, TypeError) as error:
        # An attack that cannot finish proves nothing, so it must not pass for a defence.
        return Result(attack, None, f"it could not finish: {type(error).__name__}")


def render(results: list[Result]) -> str:
    """Write the report.

    Args:
        results: What happened with each attack.

    Returns:
        The report, in Markdown.
    """
    stopped = [result for result in results if result.stopper is not None]
    lines = [
        "# Security report",
        "",
        "Generated by `python -m security` against the running stack, and checked in CI: a change in",
        "what stops an attack fails the build until someone reviews it. Nothing here calls a model.",
        "Attacks on the model itself assume the worst, with a script that does what the attacker wants,",
        "so they measure the code around the model and not how well the model resists.",
        "",
        f"**{len(stopped)} of {len(results)} attacks stopped.**",
        "",
        "## What stopped them",
        "",
        "| Defence | Attacks |",
        "| --- | ---: |",
    ]
    counts = Counter(result.stopper.value for result in stopped if result.stopper is not None)
    lines.extend(
        f"| {name} | {total} |"
        for name, total in sorted(counts.items(), key=lambda c: (-c[1], c[0]))
    )
    categories = list(dict.fromkeys(result.attack.category for result in results))
    for category in categories:
        lines.extend(["", f"## {category}", "", "| Attempt | Stopped by |", "| --- | --- |"])
        for result in results:
            if result.attack.category == category:
                stopper = (
                    result.stopper.value if result.stopper else f"**NOT STOPPED**: {result.note}"
                )
                lines.append(f"| {result.attack.goal} | {stopper} |")
    return "\n".join(lines) + "\n"
